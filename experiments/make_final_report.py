#!/usr/bin/env python3
"""results/ + docs/DECISIONS.md -> FINAL_REPORT.md (skeleton filled from files; pending where results are absent)."""
import datetime, re
from status import *  # noqa: F401,F403
from make_readme_tables import results, runtimes


def decision(tag):
    t = (ROOT / "docs/DECISIONS.md").read_text()
    m = re.search(rf"^## {tag} .*?(?=^## D|\Z)", t, re.S | re.M)
    return m.group(0).strip() if m else f"(decision {tag} not found in docs/DECISIONS.md)"


def pending_items():
    items = [f"{i}: {s} ({e})" for i, s, v, e in claims() if v == "pending"]
    todo = (ROOT / "HARDWARE_TODO.md").read_text()
    items += [l.lstrip("# ").strip() for l in todo.splitlines() if l.startswith("## ")]
    return items


c, sha = prereg()
head = (git("rev-parse", "HEAD") or "unknown").strip()
dirty = bool((git("status", "--porcelain") or "").strip())
body = f"""# mcuaccel final report

Generated by `experiments/make_final_report.py` on {datetime.date.today()} from `results/`; do not edit by hand.
Repository HEAD `{head}`{' (working tree dirty)' if dirty else ''}.

## Pre-registration (SPEC section 6)
- tag `m1` commit: `{c or 'unknown'}`
- sha256 of `results/m1_predictions.csv` at tag m1: `{sha or 'unknown'}`
- Publishing these externally (no remote exists) is a manual step: HARDWARE_TODO.md.

## Claims and verdicts
{results()}

## Deviations logged in docs/DECISIONS.md
Text copied verbatim from the decision log. Neither changes a threshold in SPEC.

{decision('D19')}

{decision('D20')}

## Pending items
""" + "\n".join(f"- {x}" for x in pending_items()) + f"""

## Reproduction cost (measured wall time, from provenance in results/)
{runtimes()}
"""
(ROOT / "FINAL_REPORT.md").write_text(body)
