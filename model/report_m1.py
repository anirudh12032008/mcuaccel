#!/usr/bin/env python3
"""Generate results/M1_PREDICTIONS.md from results/m1_predictions.csv and results/m1_summary.json.
Every number in the output is read from those two files (and driver/baseline provenance recorded in
the summary); the prose is fixed text. Usage: python model/report_m1.py [results_dir]"""
import csv
import hashlib
import json
import sys
from pathlib import Path

d = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "results")
rows = list(csv.DictReader(open(d / "m1_predictions.csv")))
S = json.loads((d / "m1_summary.json").read_text())
sha = hashlib.sha256((d / "m1_predictions.csv").read_bytes()).hexdigest()
PS = S["parameters"]["Ps"]
MODELS = list(S["models"])
ARCH_NOTE = {"os": "os (built: output stationary, x re-fetched per tile)",
             "lb": "lb (modelled only: line buffer)", "acc": "acc (modelled only: accumulator SRAM)"}


def n(x, f="{:,}"):
    return "-" if x is None else f.format(x)


def r0(x):
    return n(None if x is None else round(x))


def table(head, body):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in body]
    return "\n".join(out)


def ent(m, arch, P):
    return S["models"][m]["archs"][arch]["P"][str(P)]


L = []
a = L.append
a("# M1 pre-registered predictions")
a("")
a("**Status: FROZEN at git tag `m1`.** These are the scored predictions of SPEC claim C4 and the "
  "descriptive prediction of C5. They are generated by `model/m1.py` and `model/report_m1.py` "
  "from `results/m1_predictions.csv` and `results/m1_summary.json`; no number below is typed by "
  "hand. After tag `m1` the model may be fixed, but fixed outputs are reported as post-hoc beside "
  "these, which remain the scored ones. The RTL is not tuned to match them (SPEC §6, "
  "pre-registration rule).")
a("")
a(f"- `m1_predictions.csv` sha256: `{sha}`")
a(f"- model commit (at generation): `{S['commit']}`, date {S['date']}")
inp = S["inputs"]
a(f"- driver constants: {inp['driver']} (`drv_chain` = {S['parameters']['t_drv_chain']} cycles per "
  f"`mcuaccel_run`, `drv_patch` = {S['parameters']['t_drv_patch']} cycles per patched field; "
  f"results/driver_overhead.json)")
a(f"- bench_main window overhead: {inp['bench_window_cycles']} cycles (identical in both builds)")
for m in MODELS:
    pm = inp["per_model"][m]
    b, p = pm.get("baseline") or {}, pm.get("profile") or {}
    a(f"- {m}: baseline {n(S['models'][m]['baseline_cycles'])} cycles (`cycles_median`; commit "
      f"`{str(b.get('commit'))[:7]}`, {b.get('images')} images x {b.get('runs')} runs); software-op "
      f"profile commit `{str(p.get('commit'))[:7]}`, {p.get('images')} images x {p.get('runs')} runs; "
      f"x_align {pm['x_align_from_baseline']}")
a("")

a("## 1. Per-command STAMP at P = 8 (architecture os)")
a("")
a("STAMP = `t_cmd` = t_desc + t_wload + t_pload + t_compute + t_flush (DESIGN §6.3, §7). "
  "`cmd` is the split index. Join key for C4(a): (model, op, P, cmd).")
a("")
body = [[r["model"], r["op"], r["cmd"], r["kind"], f"{r['H']}x{r['W']}x{r['C']}->{r['O']}",
         f"{r['KH']}x{r['KW']}/{r['SH']}", n(int(r["macs"])), r["t_desc"], n(int(r["t_wload"])),
         n(int(r["t_pload"])), n(int(r["t_compute"])), r["t_flush"], n(int(r["t_cmd"])), r["util"]]
        for r in rows if r["arch"] == "os" and r["P"] == "8"]
a(table("model op cmd kind HxWxC->O K/S macs t_desc t_wload t_pload t_compute t_flush STAMP util".split(), body))
a("")

a("## 2. Per-network totals at P = 8 (architecture os)")
a("")
body = []
for m in MODELS:
    e = ent(m, "os", 8)
    body.append([m, e["n_commands"], e["n_chains"], n(e["sum_stamp"]), n(e["accel_cycles"]),
                 r0(e["sw_cycles"]), n(e["driver_cycles"]), n(e["bench_window_cycles"]),
                 n(e["accel_plus_driver_cycles"]), r0(e["predicted_model_run"]),
                 n(e["baseline_cycles"]), f"{e['predicted_speedup']:.1f}"])
a(table(["model", "commands", "chains", "sum STAMP", "accel (chains)", "software ops", "driver",
         "bench window", "accel+driver (C4b)", "predicted model_run", "baseline", "speedup"], body))
a("")
a("accel (chains) = Σ over commands of (STAMP + lam + 1) + 2 per chain. C4(b) scores "
  "`accel+driver` = accel (chains) + driver against the measured accelerated `model_run` minus "
  "the measured software ops (software and window terms are measurements, not scored). "
  "driver = chains x drv_chain + patched fields x drv_patch.")
a("")
a("Software fallback ops carried through from the profile build "
  "(cycles per inference; conv/fc ops are accelerated and excluded):")
a("")
body = []
for m in MODELS:
    for o in ent(m, "os", 8)["ops"]:
        if o["where"] == "sw":
            body.append([m, o["op"], o["kind"], r0(o["cycles"])])
a(table(["model", "op", "kind", "cycles"], body))
a("")
a("Patched descriptor fields per call (DESIGN §6.5): "
  + "; ".join(f"{m}: {ent(m, 'os', 8)['n_patches']} at P=8" for m in MODELS)
  + ". A patched field is X_ORIGIN of a command reading the network `input` and Y_BASE of a "
    "command writing `output`; a split command is patched per descriptor.")
a("")

a("## 3. Predicted speedup at every P (architecture os)")
a("")
a("speedup = baseline `cycles_median` / predicted `model_run` "
  "(= software ops + accel chains + driver + bench window).")
a("")
hd = ["model", "quantity"] + [f"P={p}" for p in PS]
body = []
for m in MODELS:
    body.append([m, "sum STAMP"] + [n(ent(m, "os", p)["sum_stamp"]) for p in PS])
    body.append([m, "accel+driver"] + [n(ent(m, "os", p)["accel_plus_driver_cycles"]) for p in PS])
    body.append([m, "predicted model_run"] + [r0(ent(m, "os", p)["predicted_model_run"]) for p in PS])
    body.append([m, "**predicted speedup**"] +
                [f"**{ent(m, 'os', p)['predicted_speedup']:.1f}**" for p in PS])
    body.append([m, "commands (splits)"] + [ent(m, "os", p)["n_commands"] for p in PS])
a(table(hd, body))
a("")
a("C1 asks for S >= 10 and C1b for S(cifar_mobilenet, P=8) >= 100; the predictions at P = 8 are "
  + ", ".join(f"{m}: {ent(m, 'os', 8)['predicted_speedup']:.1f}" for m in MODELS) + ".")
a("")

a("## 4. Predicted saturation width P* (SPEC C5)")
a("")
a("P* = smallest P in {1, 2, 4, 8, 16} whose Σ STAMP (accelerator only) is within 10 % of its "
  "value at P = 16; 16 means not reached on this grid. `P* end-to-end` applies the same rule to "
  "the predicted `model_run` (including the software term) and is descriptive only.")
a("")
body = []
for m in MODELS:
    e = S["models"][m]["archs"]["os"]
    r16 = e["P"]["16"]["sum_stamp"]
    body.append([m, e["p_star"], e["p_star_end_to_end"]] +
                [f"{e['P'][str(p)]['sum_stamp'] / r16:.3f}" for p in PS])
a(table(["model", "P*", "P* end-to-end"] + [f"STAMP(P={p}) / STAMP(16)" for p in PS], body))
a("")

a("## 5. Three-architecture comparison")
a("")
a("Same 4P multipliers and the same single 32-bit RAM port in all three; only `os` is built "
  "(DESIGN §9.2-9.4). Σ STAMP and bus read words are summed over commands; speedup uses the "
  "same software, driver and window terms as §3.")
a("")
for m in MODELS:
    a(f"**{m}**")
    a("")
    body = []
    for arch in ("os", "lb", "acc"):
        for q, key in (("sum STAMP", "sum_stamp"), ("bus read words", "bus_rd"),
                       ("MAC utilisation", "util"), ("predicted speedup", "predicted_speedup")):
            fmt = {"util": lambda v: f"{v:.3f}", "predicted_speedup": lambda v: f"{v:.1f}"}.get(key, n)
            body.append([ARCH_NOTE[arch] if q == "sum STAMP" else "", q] +
                        [fmt(ent(m, arch, p)[key]) for p in PS])
        body.append(["", "P*"] + [S["models"][m]["archs"][arch]["p_star"]] + [""] * (len(PS) - 1))
    a(table(["architecture", "quantity"] + [f"P={p}" for p in PS], body))
    a("")

a("## 6. Known model biases (written before m1; DESIGN §7.4, SPEC §6)")
a("")
a("- The +1 PSETUP cycle per pixel is hidden behind the requantizer when a layer is requant bound "
  "(T_tile = NV); the model keeps the +1 (conservative), about +3 % on cifar op_2/4/6.")
a("- The last tile's W_t and NV are counted in both T_tile and FLUSH (at most P + 3 cycles per command).")
a("- Driver constants are measured on the walking-skeleton stub (START -> DONE next cycle): they "
  "include one full poll iteration and the call site as compiled in the timing app, so with a "
  "real, longer chain they can differ by about one poll iteration; negligible against the chain "
  "times above but not zero. The CPI estimate they replace is kept in `parameters` of the summary.")
a("- STAMP is self-reported by the ctrl counter; M5/M6 cross-check against CYCLES and a VCD.")
a("- Software-op cycles come from the instrumented profile build (rdcycle around each op adds a few "
  "cycles per op) averaged over a small number of inferences; they are measurements, not scored.")
a("")
(d / "M1_PREDICTIONS.md").write_text("\n".join(L) + "\n")
print(f"wrote {d / 'M1_PREDICTIONS.md'}")
